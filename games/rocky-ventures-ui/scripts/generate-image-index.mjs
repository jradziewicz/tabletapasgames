// Writes src/lib/images/<folder>/index.ts with an explicit import for every PNG in that folder.
// The game bundle is built with Rollup, which doesn't support Vite's import.meta.glob, so the
// image lookups use these generated lists instead. Re-run after adding or removing images:
//   node scripts/generate-image-index.mjs
import { readdirSync, writeFileSync } from 'fs'
import { join } from 'path'
import { fileURLToPath } from 'url'

const imagesRoot = fileURLToPath(new URL('../src/lib/images/', import.meta.url))
const folders = ['agreements', 'cards', 'dragon', 'playerCards', 'scourges', 'shares', 'tokens']

for (const folder of folders) {
    const files = readdirSync(join(imagesRoot, folder))
        .filter((file) => file.endsWith('.png'))
        .sort()
    const lines = [
        '// Generated by scripts/generate-image-index.mjs - do not edit by hand.',
        ...files.map((file, index) => `import image${index} from './${file}'`),
        '',
        '// Image URL by file name (without .png)',
        'export const Images: Record<string, string> = {',
        ...files.map((file, index) => `    '${file.replace(/\.png$/, '')}': image${index},`),
        '}',
        ''
    ]
    writeFileSync(join(imagesRoot, folder, 'index.ts'), lines.join('\n'))
    console.log(`${folder}: ${files.length} images`)
}
